import numpy as np
import skfuzzy as fuzz
from skfuzzy import control as ctrl
import matplotlib.pyplot as plt

# ==========================================
# VARIÁVEIS DO SISTEMA FUZZY
# ==========================================

# Entrada 1: Impacto
impacto = ctrl.Antecedent(
    np.arange(0, 101, 1),
    'impacto'
)

# Entrada 2: Explorabilidade
explorabilidade = ctrl.Antecedent(
    np.arange(0, 11, 1),
    'explorabilidade'
)

# Saída: Urgência
urgencia = ctrl.Consequent(
    np.arange(0, 101, 1),
    'urgencia'
)

# ==========================================
# FUNÇÕES DE PERTINÊNCIA — IMPACTO
# ==========================================

impacto['baixo'] = fuzz.trimf(
    impacto.universe,
    [0, 0, 40]
)

impacto['medio'] = fuzz.trimf(
    impacto.universe,
    [20, 50, 80]
)

impacto['alto'] = fuzz.trimf(
    impacto.universe,
    [60, 100, 100]
)

impacto.view()
plt.show()

# ==========================================
# FUNÇÕES DE PERTINÊNCIA — EXPLORABILIDADE
# ==========================================

explorabilidade['baixa'] = fuzz.trimf(
    explorabilidade.universe,
    [0, 0, 4]
)

explorabilidade['moderada'] = fuzz.trimf(
    explorabilidade.universe,
    [2, 5, 8]
)

explorabilidade['alta'] = fuzz.trimf(
    explorabilidade.universe,
    [6, 10, 10]
)

explorabilidade.view()
plt.show()

# ==========================================
# FUNÇÕES DE PERTINÊNCIA — URGÊNCIA
# ==========================================

urgencia['baixa'] = fuzz.trimf(urgencia.universe, [0, 0, 13])
urgencia['media'] = fuzz.trimf(urgencia.universe, [20, 50, 80])
urgencia['alta'] = fuzz.trimf(urgencia.universe, [50, 70, 90])
urgencia['critica'] = fuzz.trimf(urgencia.universe, [62.5, 100, 100])

urgencia.view()
plt.show()

# ==========================================
# REGRAS FUZZY — MATRIZ 3x3
# ==========================================

# 1. Impacto baixo + Explorabilidade baixa
regra1 = ctrl.Rule(
    impacto['baixo'] & explorabilidade['baixa'],
    urgencia['baixa']
)

# 2. Impacto baixo + Explorabilidade moderada
regra2 = ctrl.Rule(
    impacto['baixo'] & explorabilidade['moderada'],
    urgencia['baixa']
)

# 3. Impacto baixo + Explorabilidade alta
regra3 = ctrl.Rule(
    impacto['baixo'] & explorabilidade['alta'],
    urgencia['media']
)

# 4. Impacto médio + Explorabilidade baixa
regra4 = ctrl.Rule(
    impacto['medio'] & explorabilidade['baixa'],
    urgencia['media']
)

# 5. Impacto médio + Explorabilidade moderada
regra5 = ctrl.Rule(
    impacto['medio'] & explorabilidade['moderada'],
    urgencia['alta']
)

# 6. Impacto médio + Explorabilidade alta
regra6 = ctrl.Rule(
    impacto['medio'] & explorabilidade['alta'],
    urgencia['alta']
)

# 7. Impacto alto + Explorabilidade baixa
regra7 = ctrl.Rule(
    impacto['alto'] & explorabilidade['baixa'],
    urgencia['critica']
)

# 8. Impacto alto + Explorabilidade moderada
regra8 = ctrl.Rule(
    impacto['alto'] & explorabilidade['moderada'],
    urgencia['critica']
)

# 9. Impacto alto + Explorabilidade alta
regra9 = ctrl.Rule(
    impacto['alto'] & explorabilidade['alta'],
    urgencia['critica']
)

# ==========================================
# SISTEMA DE INFERÊNCIA MAMDANI
# ==========================================

sistema_controle = ctrl.ControlSystem([
    regra1,
    regra2,
    regra3,
    regra4,
    regra5,
    regra6,
    regra7,
    regra8,
    regra9
])

simulador = ctrl.ControlSystemSimulation(sistema_controle)

# ==========================================
# PRIMEIRO TESTE
# ==========================================

simulador.input['impacto'] = 0
simulador.input['explorabilidade'] = 0

simulador.compute()

print(
    'Urgência:',
    round(simulador.output['urgencia'], 2),
    '%'
)

simulador.input['impacto'] = 100
simulador.input['explorabilidade'] = 10

simulador.compute()

print(f"Urgência: {simulador.output['urgencia']:.2f} %")

