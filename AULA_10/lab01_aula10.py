# Criar os valores de Impacto e Explorabilidade
impactos = np.arange(0, 101, 5)
explorabilidades = np.arange(0, 11, 1)

X, Y = np.meshgrid(impactos, explorabilidades)
Z = np.zeros_like(X, dtype=float)

# Calcular a urgência para cada combinação
for i in range(Y.shape[0]):
    for j in range(X.shape[1]):
        simulador_mom.input['impacto'] = float(X[i, j])
        simulador_mom.input['explorabilidade'] = float(Y[i, j])
        simulador_mom.compute()
        Z[i, j] = simulador_mom.output['urgencia_mom']

# Criar o gráfico 3D
fig = plt.figure(figsize=(12, 8))
ax = fig.add_subplot(111, projection='3d')

superficie = ax.plot_surface(
    X, Y, Z,
    cmap='viridis',
    edgecolor='none',
    alpha=0.9
)

ax.set_title('Superfície de Decisão — Sistema Fuzzy Mamdani (MOM)')
ax.set_xlabel('Impacto (%)')
ax.set_ylabel('Explorabilidade')
ax.set_zlabel('Urgência (%)')

fig.colorbar(superficie, ax=ax, shrink=0.6, label='Urgência (%)')
